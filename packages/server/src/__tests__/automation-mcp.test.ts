import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import {
  computeWebhookSignature,
  type CliRunner,
  type RunCommandOptions,
  type RunCommandResult,
} from '@dalang/core';
import { startDalangServer } from '../app.js';

const tempDirs: string[] = [];
function makeTempDir(prefix: string): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  tempDirs.push(dir);
  return dir;
}

afterEach(() => {
  for (const dir of tempDirs.splice(0)) {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

function createHeadlessRunner(): CliRunner {
  return {
    async which(bin) {
      if (bin === 'bwrap' || bin === 'sandbox-exec') return null;
      return `/usr/local/bin/${bin}`;
    },
    async run(cmd, args, opts: RunCommandOptions): Promise<RunCommandResult> {
      const base = path.basename(cmd).toLowerCase();
      if (args[0] === '--version') {
        return { exitCode: 0, stdout: '1.0.0\n', stderr: '', timedOut: false, idleTimedOut: false };
      }
      if (cmd.includes('claude') && args[0] === 'auth') {
        return { exitCode: 0, stdout: JSON.stringify({ loggedIn: true }), stderr: '', timedOut: false, idleTimedOut: false };
      }
      if (cmd.includes('codex') && args[0] === 'login') {
        return { exitCode: 0, stdout: 'Logged in\n', stderr: '', timedOut: false, idleTimedOut: false };
      }
      if (base === 'sh' || base === 'cmd.exe') {
        return { exitCode: 0, stdout: 'verify ok\n', stderr: '', timedOut: false, idleTimedOut: false };
      }

      const joined = `${cmd} ${args.join(' ')}`;

      const reviewMatch = joined.match(/code review round \d+ of \d+ for task ([A-Za-z0-9_-]+)/i);
      if (reviewMatch) {
        const extId = reviewMatch[1];
        const payload = JSON.stringify({
          task_id: extId,
          status: 'pass',
          verify_exit_code: 0,
          summary: `Reviewed ${extId}`,
          findings: [],
        });
        const line = joined.includes('codex')
          ? JSON.stringify({ type: 'item.completed', item: { type: 'agent_message', text: payload } })
          : JSON.stringify({ type: 'result', session_id: `rev-${extId}`, result: payload });
        opts.onStdoutLine?.(line);
        return { exitCode: 0, stdout: `${line}\n`, stderr: '', timedOut: false, idleTimedOut: false };
      }

      const taskMatch = joined.match(/You are executing task ([A-Za-z0-9_-]+):/);
      if (taskMatch) {
        const extId = taskMatch[1];
        const resPathMatch = joined.match(/"(\.dalang\/[^\"]+result\.json)"/);
        const relResult = resPathMatch?.[1] ?? `.dalang/tasks/${extId}/result.json`;
        const fileName = joined.includes('nightly-deps')
          ? 'deps.txt'
          : joined.includes('webhook-sync')
            ? 'webhook.txt'
            : 'terminal-agent.txt';
        fs.writeFileSync(path.join(opts.cwd, fileName), `generated by ${extId}\n`);
        const absRes = path.join(opts.cwd, relResult);
        fs.mkdirSync(path.dirname(absRes), { recursive: true });
        fs.writeFileSync(
          absRes,
          JSON.stringify({
            task_id: extId,
            status: 'completed',
            changed_files: [fileName],
            summary: `Created ${fileName}`,
          }),
        );
        const line = joined.includes('codex')
          ? JSON.stringify({ type: 'item.completed', item: { type: 'agent_message', text: 'ok' } })
          : JSON.stringify({ type: 'result', session_id: `c-${extId}`, result: 'ok' });
        opts.onStdoutLine?.(line);
        return { exitCode: 0, stdout: `${line}\n`, stderr: '', timedOut: false, idleTimedOut: false };
      }

      return { exitCode: 0, stdout: '', stderr: '', timedOut: false, idleTimedOut: false };
    },
  };
}

describe('v0.11 Automation & Outside Agents over loopback MCP (real HTTP)', () => {
  it('completes a scheduled run, a signed webhook run, and a terminal-agent MCP run without opening the UI', async () => {
    const dbDir = makeTempDir('dalang-v011-db-');
    const projDir = path.join(makeTempDir('dalang-v011-proj-'), 'auto-app');
    const server = await startDalangServer({
      port: 0,
      dbPath: path.join(dbDir, 'dalang.db'),
      runner: createHeadlessRunner(),
      enableScheduler: false,
    });

    try {
      // Switch reviewer to claude-code so automated review runs without agy keyring
      await fetch(`${server.url}/api/profiles/profile-reviewer`, {
        method: 'PATCH',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ provider: 'claude-code', model: '' }),
      });

      const projRes = await fetch(`${server.url}/api/projects`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ mode: 'create', name: 'Auto App', path: projDir }),
      });
      expect(projRes.status).toBe(201);
      const { project } = (await projRes.json()) as { project: { id: string } };

      // 1. Scheduled run finishes without opening the UI (auto-merges onto main)
      const schedCreate = await fetch(`${server.url}/api/automations`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          projectId: project.id,
          name: 'Nightly dependency check',
          kind: 'schedule',
          cronExpr: '*/5 * * * *',
          title: 'nightly-deps update',
          prompt: 'Run nightly-deps update and write deps.txt',
          filesAllowed: ['deps.txt'],
          acceptanceCriteria: ['deps.txt created'],
          verify: 'echo ok',
          allowUnconfined: true,
          autoMerge: true,
        }),
      });
      expect(schedCreate.status).toBe(201);
      const { automation: scheduleAuto } = (await schedCreate.json()) as {
        automation: { id: string; nextRunAt: string };
      };
      expect(scheduleAuto.nextRunAt).toBeTruthy();

      // Advance clock past nextRunAt and tick the scheduler
      const dueTime = new Date(new Date(scheduleAuto.nextRunAt).getTime() + 1000);
      const ticked = await server.automationService.tick(dueTime);
      expect(ticked).toHaveLength(1);
      const schedRun = await server.automationService.waitForRun(ticked[0].id);
      expect(schedRun?.status).toBe('completed');
      expect(fs.existsSync(path.join(projDir, 'deps.txt'))).toBe(true);

      // 2. Signed webhook run (and invalid signature rejection) even with app password login enabled
      const hookCreate = await fetch(`${server.url}/api/automations`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          projectId: project.id,
          name: 'CI Webhook',
          kind: 'webhook',
          title: 'webhook-sync task',
          prompt: 'Run webhook-sync for {{event}}: {{payload}}',
          filesAllowed: ['webhook.txt'],
          acceptanceCriteria: ['webhook.txt created'],
          verify: 'echo ok',
          allowUnconfined: true,
          autoMerge: true,
        }),
      });
      expect(hookCreate.status).toBe(201);
      const { automation: hookAuto } = (await hookCreate.json()) as {
        automation: { id: string; webhookUrl: string; webhookSecret: string };
      };
      expect(hookAuto.webhookUrl).toContain(`${server.url}/api/webhooks/`);
      expect(hookAuto.webhookSecret.length).toBeGreaterThanOrEqual(32);

      // Create read-only & full-access external MCP tokens before enabling login
      const roRes = await fetch(`${server.url}/api/mcp-tokens`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ name: 'Claude RO', accessLevel: 'read-only' }),
      });
      expect(roRes.status).toBe(201);
      const roToken = (await roRes.json()) as { token: string; tokenInfo: { id: string }; endpointUrl: string };

      const rwRes = await fetch(`${server.url}/api/mcp-tokens`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ name: 'Codex Full', accessLevel: 'full-access' }),
      });
      expect(rwRes.status).toBe(201);
      const rwToken = (await rwRes.json()) as { token: string; tokenInfo: { id: string }; endpointUrl: string };
      expect(rwToken.endpointUrl).toBe(`${server.url}/mcp`);

      // Enable DALANG password login to verify webhooks & /mcp still work with their own auth while management APIs require login
      const enableLogin = await fetch(`${server.url}/api/auth/settings`, {
        method: 'PUT',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ enabled: true, password: 'a long automation password' }),
      });
      expect(enableLogin.status).toBe(200);
      const cookie = (enableLogin.headers.get('set-cookie') ?? '').split(';')[0];

      // Unauthenticated management API is rejected
      expect((await fetch(`${server.url}/api/automations`)).status).toBe(401);
      expect((await fetch(`${server.url}/api/mcp-tokens`)).status).toBe(401);

      // Unsigned & wrongly-signed webhook calls are rejected with 401
      const payloadStr = JSON.stringify({ ref: 'refs/heads/main', commit: 'abc123' });
      const badSigRes = await fetch(hookAuto.webhookUrl, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'X-Hub-Signature-256': 'sha256=' + 'a'.repeat(64),
        },
        body: payloadStr,
      });
      expect(badSigRes.status).toBe(401);

      // Valid HMAC-SHA256 signature triggers the webhook automation
      const validSig = computeWebhookSignature(hookAuto.webhookSecret, payloadStr);
      const goodHookRes = await fetch(hookAuto.webhookUrl, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'X-Hub-Signature-256': validSig,
          'X-GitHub-Event': 'push',
        },
        body: payloadStr,
      });
      expect(goodHookRes.status).toBe(202);
      const { run: hookRun } = (await goodHookRes.json()) as { run: { id: string } };
      const finishedHook = await server.automationService.waitForRun(hookRun.id);
      expect(finishedHook?.status).toBe('completed');
      expect(fs.existsSync(path.join(projDir, 'webhook.txt'))).toBe(true);

      // 3. Outside terminal agent over real HTTP /mcp
      // Read-only token can list projects, cannot start tasks
      const roList = await fetch(`${server.url}/mcp`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${roToken.token}` },
        body: JSON.stringify({
          jsonrpc: '2.0',
          id: 1,
          method: 'tools/call',
          params: { name: 'list_projects', arguments: {} },
        }),
      });
      expect(roList.status).toBe(200);
      const roListJson = (await roList.json()) as { result: { isError: boolean; content: Array<{ text: string }> } };
      expect(roListJson.result.isError).toBe(false);
      expect(roListJson.result.content[0].text).toContain('Auto App');

      const roDenied = await fetch(`${server.url}/mcp`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${roToken.token}` },
        body: JSON.stringify({
          jsonrpc: '2.0',
          id: 2,
          method: 'tools/call',
          params: {
            name: 'start_task',
            arguments: { project_id: project.id, title: 'Blocked', prompt: 'Should fail', verify: 'echo ok' },
          },
        }),
      });
      expect(roDenied.status).toBe(200);
      expect(((await roDenied.json()) as { result: { isError: boolean } }).result.isError).toBe(true);

      // Full-access token starts a task and merges it without ever opening the UI
      const initRes = await fetch(`${server.url}/mcp`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${rwToken.token}` },
        body: JSON.stringify({ jsonrpc: '2.0', id: 10, method: 'initialize', params: {} }),
      });
      expect(initRes.status).toBe(200);

      const startTaskRes = await fetch(`${server.url}/mcp`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${rwToken.token}` },
        body: JSON.stringify({
          jsonrpc: '2.0',
          id: 11,
          method: 'tools/call',
          params: {
            name: 'start_task',
            arguments: {
              project_id: project.id,
              title: 'Create terminal-agent file',
              prompt: 'Write terminal-agent.txt',
              files_allowed: ['terminal-agent.txt'],
              verify: 'echo ok',
              allow_unconfined: true,
              auto_merge: true,
              mode: 'wait',
            },
          },
        }),
      });
      expect(startTaskRes.status).toBe(200);
      const startTaskJson = (await startTaskRes.json()) as {
        result: { isError: boolean; content: Array<{ text: string }> };
      };
      expect(startTaskJson.result.isError).toBe(false);
      const snap = JSON.parse(startTaskJson.result.content[0].text) as { status: string };
      expect(snap.status).toBe('done');
      expect(fs.existsSync(path.join(projDir, 'terminal-agent.txt'))).toBe(true);

      // Revoking the token via authenticated management API immediately rejects subsequent /mcp calls
      const revokeRes = await fetch(`${server.url}/api/mcp-tokens/${rwToken.tokenInfo.id}/revoke`, {
        method: 'POST',
        headers: { cookie },
      });
      expect(revokeRes.status).toBe(200);

      const afterRevoke = await fetch(`${server.url}/mcp`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${rwToken.token}` },
        body: JSON.stringify({ jsonrpc: '2.0', id: 12, method: 'ping' }),
      });
      expect(afterRevoke.status).toBe(401);
    } finally {
      await server.close();
    }
  });
});
